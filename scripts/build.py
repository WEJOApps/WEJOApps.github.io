#!/usr/bin/env python3
"""Build the multilingual site from src/ into the repository root.

    python3 scripts/build.py

- src/layout.html            page shell (header, footer, <head>)
- src/i18n.json              UI strings, page titles and descriptions per language
- src/content/<lang>/*.html  page body (the inside of <main>) per language

English is the default language and has no URL prefix (/courseboy/privacy/);
other languages get one (/ko/courseboy/privacy/).

Content placeholders:
    {{url:<page key>}}  link to that page in the same language
    {{email}}           contact email as a mailto link
    {{app_store_url}}   CourseBoy App Store page
"""
import json
import re
from html import escape
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

SITE_URL = "https://wejoapps.github.io"
LANGS = ["en", "ko", "ja", "de", "fr"]
DEFAULT_LANG = "en"
EMAIL = "peter.iosdev@gmail.com"
APP_STORE_ID = "6828766049"

# Page key -> (URL path, section). The section picks the header nav and extras.
PAGES = {
    "home": ("/", "site"),
    "courseboy": ("/courseboy/", "courseboy"),
    "courseboy/support": ("/courseboy/support/", "courseboy"),
    "courseboy/privacy": ("/courseboy/privacy/", "courseboy"),
    "courseboy/terms": ("/courseboy/terms/", "courseboy"),
}
DOC_PAGES = {"courseboy", "courseboy/support", "courseboy/privacy", "courseboy/terms"}

CURRENT_PAGE = ' aria-current="page"'
CURRENT_LANG = ' aria-current="true"'
GENERATED_NOTE ="<!-- Generated by scripts/build.py from src/. Edit the source, not this file. -->"


def url_for(lang, key):
    path = PAGES[key][0]
    return path if lang == DEFAULT_LANG else f"/{lang}{path}"


def out_file(lang, key):
    rel = url_for(lang, key).strip("/")
    return ROOT / rel / "index.html" if rel else ROOT / "index.html"


def expand(text, lang):
    def repl(match):
        name = match.group(1)
        if name.startswith("url:"):
            return url_for(lang, name[4:])
        if name == "email":
            return f'<a href="mailto:{EMAIL}">{EMAIL}</a>'
        if name == "app_store_url":
            return f"https://apps.apple.com/app/id{APP_STORE_ID}"
        raise KeyError(f"unknown placeholder {{{{{name}}}}}")

    return re.sub(r"\{\{([\w:/]+)\}\}", repl, text)


def indent(lines, spaces):
    return "\n".join(" " * spaces + line for line in lines)


def nav_html(lang, key, strings):
    section = PAGES[key][1]
    if section == "site":
        items = [("#apps", strings["nav"]["apps"], False), ("#contact", strings["nav"]["contact"], False)]
    else:
        items = [
            (url_for(lang, k), strings["nav"][k.split("/")[1]], k == key)
            for k in ("courseboy/support", "courseboy/privacy", "courseboy/terms")
        ]
    links = [
        f'  <a href="{href}"{CURRENT_PAGE if current else ""}>{escape(label)}</a>' for href, label, current in items
    ]
    return indent(["<nav class=\"site-nav\">", *links, "</nav>"], 8)


def lang_menu_html(lang, key, i18n):
    links = [
        f'    <li><a href="{url_for(l, key)}" hreflang="{l}" lang="{l}"'
        f'{CURRENT_LANG if l == lang else ""}>{escape(i18n[l]["name"])}</a></li>'
        for l in LANGS
    ]
    return indent(
        [
            '<details class="lang-menu">',
            f'  <summary aria-label="{escape(i18n[lang]["language_label"])}">{lang.upper()}</summary>',
            "  <ul>",
            *links,
            "  </ul>",
            "</details>",
        ],
        8,
    )


def head_extra(lang, key, i18n):
    lines = [f'<link rel="canonical" href="{SITE_URL}{url_for(lang, key)}">']
    lines += [f'<link rel="alternate" hreflang="{l}" href="{SITE_URL}{url_for(l, key)}">' for l in LANGS]
    lines.append(f'<link rel="alternate" hreflang="x-default" href="{SITE_URL}{url_for(DEFAULT_LANG, key)}">')
    page = i18n[lang]["pages"][key]
    lines += [
        '<meta property="og:type" content="website">',
        f'<meta property="og:title" content="{escape(page["title"])}">',
        f'<meta property="og:description" content="{escape(page["description"])}">',
        f'<meta property="og:url" content="{SITE_URL}{url_for(lang, key)}">',
        f'<meta property="og:locale" content="{i18n[lang]["og_locale"]}">',
    ]
    if PAGES[key][1] == "courseboy":
        lines.append(f'<meta name="apple-itunes-app" content="app-id={APP_STORE_ID}">')
    return indent(lines, 2)


def render_page(layout, i18n, lang, key):
    strings = i18n[lang]
    page = strings["pages"][key]
    section = PAGES[key][1]
    content = (SRC / "content" / lang / f"{key}.html").read_text(encoding="utf-8")
    return layout.substitute(
        lang=lang,
        title=escape(page["title"]),
        description=escape(page["description"]),
        generated_note=GENERATED_NOTE,
        head_extra=head_extra(lang, key, i18n),
        logo_href=url_for(lang, "courseboy" if section == "courseboy" else "home"),
        logo="CourseBoy" if section == "courseboy" else "WEJOApps",
        nav=nav_html(lang, key, strings),
        lang_menu=lang_menu_html(lang, key, i18n),
        main_attr=' class="container doc"' if key in DOC_PAGES else "",
        content=expand(content.rstrip(), lang),
        home_href=url_for(lang, "home"),
    )


def render_404(layout, i18n):
    # GitHub Pages serves /404.html for every missing path, so it lists all languages.
    content = (SRC / "content" / "404.html").read_text(encoding="utf-8")
    homes = "\n".join(
        f'        <li><a href="{url_for(l, "home")}" lang="{l}">{escape(i18n[l]["name"])}</a></li>' for l in LANGS
    )
    return layout.substitute(
        lang=DEFAULT_LANG,
        title="404 | WEJOApps",
        description="Page not found",
        generated_note=GENERATED_NOTE,
        head_extra='  <meta name="robots" content="noindex">',
        logo_href="/",
        logo="WEJOApps",
        nav="",
        lang_menu="",
        main_attr=' class="not-found"',
        content=content.rstrip().replace("{{home_links}}", homes),
        home_href="/",
    )


def render_sitemap():
    entries = []
    for key in PAGES:
        alternates = "\n".join(
            f'    <xhtml:link rel="alternate" hreflang="{l}" href="{SITE_URL}{url_for(l, key)}"/>' for l in LANGS
        )
        for lang in LANGS:
            entries.append(f"  <url>\n    <loc>{SITE_URL}{url_for(lang, key)}</loc>\n{alternates}\n  </url>")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
        'xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' + "\n".join(entries) + "\n</urlset>\n"
    )


def main():
    layout = Template((SRC / "layout.html").read_text(encoding="utf-8"))
    i18n = json.loads((SRC / "i18n.json").read_text(encoding="utf-8"))

    written = []
    for lang in LANGS:
        for key in PAGES:
            path = out_file(lang, key)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(render_page(layout, i18n, lang, key), encoding="utf-8")
            written.append(path)

    (ROOT / "404.html").write_text(render_404(layout, i18n), encoding="utf-8")
    (ROOT / "sitemap.xml").write_text(render_sitemap(), encoding="utf-8")
    written += [ROOT / "404.html", ROOT / "sitemap.xml"]

    for path in written:
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
